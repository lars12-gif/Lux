export function getForm(key) {
  const aliases = {
    s: 'eventS', small: 'eventS', m: 'eventM', medium: 'eventM',
    l: 'eventL', large: 'eventL', استقبال: 'welcome', ترحيب: 'welcome',
    ورْك: 'work', work: 'work', فعالية_s: 'eventS', فعالية_m: 'eventM',
    فعالية_l: 'eventL', فائز: 'winner', نتائج: 'winner',
    ترقية: 'promotion', اعلان: 'announcement', نقاط: 'points',
    عضو: 'member', تسجيل: 'member'
  };
  const k = aliases[String(key || '').toLowerCase()] || key;
  return FORM_TEMPLATES[k] ? FORM_TEMPLATES[k]() : null;
}

